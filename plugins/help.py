"""
أوامر المساعدة ❓
"""
from telethon import events

def register(client):
    """تسجيل أوامر المساعدة"""
    
    @client.on(events.NewMessage(outgoing=True, pattern=r'اوامر'))
    async def help_command(event):
        """عرض قائمة الأوامر"""
        help_text = """
**🤖 أوامر البوت**

**🎭 الانتحال:**
• `انتحال` - رد على رسالة لانتحال الشخص
• `اسم أحمد محمد` - تغيير اسمك
• `حالة نص` - تغيير حالتك
• `صورة` - رد على صورة لتغيير صورتك
• `رجوع` - استعادة بياناتك الأصلية

**💬 الرسائل:**
• `قل نص` - إرسال رسالة عادية
• `حذف` - رد على رسالة لحذفها
• `تعديل نص` - رد على رسالتك لتعديلها

**❓ مساعدة:**
• `اوامر` - عرض هذه القائمة
"""
        await event.edit(help_text)
