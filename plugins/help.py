"""
أوامر المساعدة ❓
"""
from telethon import events

def register(client):
    """تسجيل أوامر المساعدة"""
    
    @client.on(events.NewMessage(outgoing=True, pattern=r'اوامر'))
    async def help_command(event):
        """عرض قائمة أوامر الحساب"""
        help_text = """
**🤖 أوامر الحساب**

**👁️ المراقبة:**
• `مراقبة` - تفعيل المراقبة (داخل المجموعة)
• `مراقبة -100xxx` - تفعيل بالآيدي
• `الغاء مراقبة` - إيقاف المراقبة (داخل المجموعة)
• `الغاء -100xxx` - إيقاف بالآيدي
• `فحص اعضاء` - حفظ جميع الأعضاء
• `اصلاح مراقبة` - إصلاح مجموعة المتغيرات
• `اصلاح -100xxx` - إصلاح بالآيدي

**📋 البيانات:**
• `المجموعات` - عرض المجموعات المراقبة
• `اعضاء` - عرض الأعضاء المحفوظين
• `عضو 123456` - تفاصيل عضو
• `سجل 123456` - سجل تغييرات عضو
• `تصدير` - تصدير البيانات كملف

**🔍 البحث:**
• `بحث 123456789` - البحث عن شخص بالآيدي

**🧠 الذكاء الاصطناعي:**
• `ذكاء سؤالك` - اسأل الذكاء الاصطناعي

**📂 السجلات:**
• `.logs` - إرسال ملف سجلات البوت

**❓ مساعدة:**
• `اوامر` - أوامر الحساب
• `.اوامر` - أوامر Owner
"""
        await event.edit(help_text)
    
    @client.on(events.NewMessage(outgoing=True, pattern=r'^\.اوامر$'))
    async def owner_help_command(event):
        """عرض قائمة أوامر Owner"""
        help_text = """
**🎮 أوامر Owner (عن بُعد)**

**👁️ المراقبة:**
• `.مراقبة -100xxx` - تفعيل المراقبة عن بُعد
• `.فحص -100xxx` - فحص الأعضاء عن بُعد
• `.الغاء -100xxx` - إيقاف المراقبة عن بُعد
• `.اصلاح -100xxx` - إصلاح مجموعة المتغيرات

**📋 البيانات:**
• `.المجموعات` - عرض المجموعات المراقبة
• `.اعضاء` - عرض الأعضاء المحفوظين
• `.عضو 123456` - تفاصيل عضو
• `.سجل 123456` - سجل تغييرات عضو

**🔍 البحث:**
• `.بحث 123456789` - البحث بالآيدي
• `.بحث @username` - البحث باليوزر

**🧠 الذكاء الاصطناعي:**
• `.ذكاء سؤالك` - اسأل الذكاء الاصطناعي

**❓ مساعدة:**
• `.اوامر` - أوامر Owner
"""
        await event.edit(help_text)
